#!/usr/bin/env bash
# Auto-assigns non-colliding docker compose ports (DB_PORT/BACKEND_PORT/FRONTEND_PORT)
# per git worktree, so multiple Claude sessions can each run `docker compose up`
# concurrently without colliding on the default 3000/8080/5432.
#
# Fires on SessionStart and WorktreeCreate (see .claude/settings.json). Writes
# a git-ignored .env in the worktree root; never overwrites an existing one.
set -euo pipefail

TOPLEVEL="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0
COMMON_DIR="$(git rev-parse --git-common-dir 2>/dev/null)" || exit 0
case "$COMMON_DIR" in
  /*) : ;;
  *) COMMON_DIR="$TOPLEVEL/$COMMON_DIR" ;;
esac

ENV_FILE="$TOPLEVEL/.env"

# Never clobber a .env a human (or an earlier run) already created.
if [ -e "$ENV_FILE" ]; then
  exit 0
fi

REGISTRY="$COMMON_DIR/claude-worktree-ports.tsv"
LOCKDIR="$COMMON_DIR/claude-worktree-ports.lock"
touch "$REGISTRY" 2>/dev/null || true

# mkdir is atomic on both macOS and Linux (flock isn't available on macOS by
# default). Bound the wait so a lock left by a crashed process can't hang
# future sessions forever.
got_lock=0
for _ in $(seq 1 50); do
  if mkdir "$LOCKDIR" 2>/dev/null; then
    got_lock=1
    break
  fi
  sleep 0.1
done
if [ "$got_lock" -eq 1 ]; then
  trap 'rmdir "$LOCKDIR" 2>/dev/null || true' EXIT
fi

SLOT="$(awk -F'\t' -v wt="$TOPLEVEL" '$1==wt {print $2}' "$REGISTRY" | tail -1)"
if [ -z "$SLOT" ]; then
  LAST="$(awk -F'\t' '{print $2}' "$REGISTRY" | sort -n | tail -1)"
  SLOT=$(( ${LAST:-(-1)} + 1 ))
  printf '%s\t%s\n' "$TOPLEVEL" "$SLOT" >> "$REGISTRY"
fi

DB_PORT=$((5432 + SLOT))
BACKEND_PORT=$((8080 + SLOT))
FRONTEND_PORT=$((3000 + SLOT))

cat > "$ENV_FILE" <<EOF
# Auto-generated by .claude/hooks/assign-dev-ports.sh (SessionStart/WorktreeCreate hook).
# Gives this worktree its own docker compose ports so it can run alongside
# other worktrees/sessions without colliding on 3000/8080/5432.
# Safe to edit; delete this file to get a freshly assigned slot next session.
DB_PORT=$DB_PORT
BACKEND_PORT=$BACKEND_PORT
FRONTEND_PORT=$FRONTEND_PORT
BACKEND_DOMAIN=http://localhost:$BACKEND_PORT
OPS_FRONTEND_URL=http://localhost:$FRONTEND_PORT
EOF

printf '{"systemMessage": "Dev ports assigned for this worktree: frontend=%s backend=%s db=%s (see .env)"}\n' \
  "$FRONTEND_PORT" "$BACKEND_PORT" "$DB_PORT"
