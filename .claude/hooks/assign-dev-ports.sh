#!/usr/bin/env bash
# Auto-assigns non-colliding docker compose ports (DB_PORT/BACKEND_PORT/FRONTEND_PORT)
# per git worktree, so multiple Claude sessions can each run `docker compose up`
# concurrently without colliding on the default 3000/8080/5432.
#
# Fires on SessionStart and WorktreeCreate (see .claude/settings.json). Writes
# a git-ignored .env in the worktree root; never overwrites an existing one.
#
# Set OPRE_OPS_DISABLE_DEV_PORT_HOOK=1 in your shell profile to opt out.
set -euo pipefail

if [ -n "${OPRE_OPS_DISABLE_DEV_PORT_HOOK:-}" ]; then
  exit 0
fi

TOPLEVEL="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0
ENV_FILE="$TOPLEVEL/.env"

# Never clobber a .env a human (or an earlier run) already created.
if [ -e "$ENV_FILE" ]; then
  exit 0
fi

# Deterministic slot derived from the worktree's absolute path. No shared
# counter or lock file needed, and (unlike a shared registry) it doesn't
# restart from 0 for every separate clone on the same machine. Small chance
# two unrelated worktrees hash to the same slot -- acceptable for a dev
# convenience, not a correctness guarantee.
SLOT=$(( $(printf '%s' "$TOPLEVEL" | cksum | awk '{print $1}') % 1000 ))

DB_PORT=$((5432 + SLOT))
BACKEND_PORT=$((8080 + SLOT))
FRONTEND_PORT=$((3000 + SLOT))

cat > "$ENV_FILE" <<EOF
# Auto-generated by .claude/hooks/assign-dev-ports.sh -- see that file for details.
# SLOT is a pure hash of this worktree's path, so re-deriving (delete this file
# and start a new session) always gives back these same values. To actually
# change a port -- e.g. one collides with an unrelated local service -- hand-edit
# the line below instead.
DB_PORT=$DB_PORT
BACKEND_PORT=$BACKEND_PORT
FRONTEND_PORT=$FRONTEND_PORT
BACKEND_DOMAIN=http://localhost:$BACKEND_PORT
COMPOSE_PROJECT_NAME=ops-$SLOT
EOF

printf '{"systemMessage": "Dev ports assigned for this worktree: frontend=%s backend=%s db=%s (see .env)"}\n' \
  "$FRONTEND_PORT" "$BACKEND_PORT" "$DB_PORT"
