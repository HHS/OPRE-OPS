#!/usr/bin/env bash
# Auto-assigns non-colliding docker compose ports (DB_PORT/BACKEND_PORT/FRONTEND_PORT)
# per linked git worktree, so multiple Claude sessions can each run `docker compose up`
# concurrently without colliding on the default 3000/8080/5432.
#
# Runs on SessionStart startup/resume (see .claude/settings.json). Only acts in a linked
# worktree of this repository, never in the main checkout, and never overwrites an existing
# .env (git-ignored). Run it by hand from a worktree to generate the .env yourself.
#
# Opt out with OPRE_OPS_DISABLE_DEV_PORT_HOOK=1, set in your shell profile or in the "env"
# block of ~/.claude/settings.json (the Desktop app may not load your shell profile).
set -euo pipefail

if [ "${OPRE_OPS_DISABLE_DEV_PORT_HOOK:-}" = "1" ]; then
  exit 0
fi

# Claude Desktop runs hooks in the main checkout, so take the session's directory from the
# hook input's `cwd` field when there is one, and fall back to the current directory.
INPUT=""
[ -t 0 ] || INPUT="$(cat)"
HOOK_CWD=""
if [ -n "$INPUT" ]; then
  if command -v jq >/dev/null 2>&1; then
    HOOK_CWD="$(printf '%s' "$INPUT" | jq -r '.cwd // empty' 2>/dev/null || true)"
  elif command -v python3 >/dev/null 2>&1; then
    HOOK_CWD="$(printf '%s' "$INPUT" | python3 -c 'import json, sys; print(json.load(sys.stdin).get("cwd") or "")' 2>/dev/null || true)"
  fi
fi
if [ -n "$HOOK_CWD" ]; then
  cd "$HOOK_CWD" 2>/dev/null || exit 0
fi

TOPLEVEL="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0

# A linked worktree has its own git dir (.git/worktrees/<name>); the main checkout's git
# dir is the common dir. Leave the main checkout on the documented default ports.
WORKTREE_GIT_DIR="$(cd "$(git rev-parse --git-dir)" && pwd -P)"
COMMON_DIR="$(cd "$(git rev-parse --git-common-dir)" && pwd -P)"
if [ "$WORKTREE_GIT_DIR" = "$COMMON_DIR" ]; then
  exit 0
fi

# Only act on worktrees of this repository, not another repo the session has cd'd into.
if [ -n "${CLAUDE_PROJECT_DIR:-}" ]; then
  PROJECT_COMMON_DIR="$(cd "$CLAUDE_PROJECT_DIR" && cd "$(git rev-parse --git-common-dir 2>/dev/null)" && pwd -P)" || exit 0
  [ "$PROJECT_COMMON_DIR" = "$COMMON_DIR" ] || exit 0
fi

ENV_FILE="$TOPLEVEL/.env"

# Never clobber a .env a human (or an earlier run) already created.
if [ -e "$ENV_FILE" ]; then
  exit 0
fi

# Deterministic slot derived from the worktree's absolute path, so no shared counter or lock
# file is needed. Each service gets its own range, all above Chrome's highest blocked port
# (10080) and below the ephemeral port ranges, so services never collide with each other or
# with the main checkout's defaults. Two worktrees share ports only if their paths land on
# the same slot (about 1 in 7000); the Compose project name uses the full hash, so they
# still won't share containers.
HASH=$(printf '%s' "$TOPLEVEL" | cksum | awk '{print $1}')
SLOT=$(( HASH % 7000 ))

FRONTEND_PORT=$((10100 + SLOT))
BACKEND_PORT=$((17100 + SLOT))
DB_PORT=$((24100 + SLOT))

cat > "$ENV_FILE" <<EOF
# Auto-generated by .claude/hooks/assign-dev-ports.sh -- see that file for details.
# The values are a pure hash of this worktree's path, so deleting this file and
# starting a new session gives back the same values. To actually change a port --
# e.g. one collides with an unrelated local service -- hand-edit the line below.
DB_PORT=$DB_PORT
BACKEND_PORT=$BACKEND_PORT
FRONTEND_PORT=$FRONTEND_PORT
BACKEND_DOMAIN=http://localhost:$BACKEND_PORT
COMPOSE_PROJECT_NAME=ops-$HASH
EOF

printf '{"systemMessage": "Dev ports assigned for this worktree: frontend=%s backend=%s db=%s (see .env)"}\n' \
  "$FRONTEND_PORT" "$BACKEND_PORT" "$DB_PORT"
